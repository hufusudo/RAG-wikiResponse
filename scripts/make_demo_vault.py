"""生成演示 Vault（demo_vault/），用于无个人笔记时的快速体验。

用法：python scripts/make_demo_vault.py
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "demo_vault"

NOTES = {
    "数据结构/红黑树.md": """# 红黑树

红黑树是一种自平衡二叉搜索树，通过红黑着色约束保证从根到叶子的最长路径
不超过最短路径的两倍，从而保证查找、插入、删除均为 O(log n)。

## 五条性质
1. 每个节点是红色或黑色
2. 根节点是黑色
3. 叶子节点（NIL）是黑色
4. 红色节点的两个子节点都是黑色（不存在连续红节点）
5. 从任一节点到其所有后代叶子的路径包含相同数目的黑色节点

插入后通过旋转与变色恢复平衡；删除同理。
与 AVL 树相比，红黑树平衡更宽松，旋转次数更少，综合增删改查性能更好。
""",
    "数据结构/AVL树.md": """# AVL 树

AVL 树是严格平衡的二叉搜索树：任意节点左右子树高度差不超过 1。

- 查找更稳定（树高更矮）
- 插入删除可能引发 O(log n) 次旋转
- 适合读多写少场景；写多场景红黑树更优
""",
    "计算机组成原理/中断机制.md": """# 异常与中断机制

中断（interrupt）让 CPU 能响应异步外部事件；异常（exception）来自
指令执行内部的同步事件（缺页、除零、系统调用）。

## 处理流程
1. 中断源发出请求
2. 中断控制器仲裁并上报 CPU
3. CPU 保护现场，查中断向量表跳转处理程序
4. 处理完成后恢复现场返回

中断优先级与嵌套：高优先级可以打断低优先级处理程序。
""",
    "计算机组成原理/流水线.md": """# 流水线

指令流水线把一条指令的执行划分为取指、译码、执行、访存、写回五个阶段，
各阶段并行处理不同指令，提高吞吐率。

冒险（hazard）三类：
- 结构冒险：硬件资源冲突
- 数据冒险：后续指令依赖前序指令结果
- 控制冒险：分支指令改变执行流

流水线吞吐率受最慢级（瓶颈级）限制。
""",
    "学习方法.md": """# 费曼学习法

费曼技巧：把要学的概念讲给完全不懂的外行听，讲不清楚的地方就是理解缺口。

1. 选定概念，白纸写下标题
2. 用最简单的话解释（避免行话）
3. 卡壳处回看原始材料
4. 简化并类比例子，重复直到流畅
""",
}


def main() -> None:
    for rel, content in NOTES.items():
        p = ROOT / "raw" / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
    print(f"演示 Vault 已生成: {ROOT}")
    print("打开方式：启动应用后在欢迎页输入该路径")


if __name__ == "__main__":
    main()
